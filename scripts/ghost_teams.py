#!/usr/bin/env python3
"""ghost_teams.py -- ghost teams: sides made of players from all over the database.

    python3 scripts/ghost_teams.py                 # print each team
    python3 scripts/ghost_teams.py --c src/ghost_teams_data.c

One rule so far, BEST XI: the most expensive club player at every position of a 4-4-2
(ties by headline skills -- a player's price IS his seven skills' sum, so it cannot break a
tie; the flag the squad screen lists a skill by can), and as reserves the next best goalkeeper, defender, midfielder,
winger and attacker. Clubs only: no national side, custom team or euro-cup copy.

The C file holds REFERENCES -- each player's team file, team, player number and both
names -- never the players themselves: the original game's data is not in this repository.
The game builds the team from the player's own database (src/ghost_teams.c) and checks the
names. The kits are copied from real teams (KITS below). Rerun after the database changes;
docs/CHALLENGE_CUP.md.

--teams DIR is the database's JSON (default: <assets>/data_json/teams, or $SWOS_ASSETS).
"""
import argparse
import glob
import json
import os
import sys

CUSTOM_FILE = 72
POSITIONS = ["GK", "RB", "LB", "D", "RW", "LW", "M", "A"]
GK, RB, LB, D, RW, LW, M, A = range(8)

# A 4-4-2 as the team files order it (slot 0..10), then the bench (11..15).
LINEUP_442 = [GK, RB, D, D, LB, RW, M, M, LW, A, A]
BENCH = [GK, D, M, (RW, LW), A]        # a tuple: the best of either

TEAMS = {
    "BEST XI": {
        "coach": "OPENSWOS",
        "home_kit": ("ITALY", "JUVENTUS", "primary"),
        "away_kit": ("SPAIN", "BARCELONA", "primary"),
    },
}
KIT_FIELDS = ["shirt_type", "stripes_color", "basic_color", "shorts_color", "socks_color"]


def default_teams_dir():
    assets = os.environ.get("SWOS_ASSETS")
    if not assets:
        assets = os.path.join(os.path.expanduser("~"), "Documents", "SWOS", "assets")
    return os.path.join(assets, "data_json", "teams")


SKILLS = ("passing", "velocity", "heading", "tackling", "control", "speed", "finishing")


def headline_skills(p):
    """How many of the seven carry the flag (8) the squad screen lists a player by."""
    return sum(1 for k in SKILLS if p[k] & 8)


def read(teams_dir):
    players, teams = [], {}
    for path in sorted(glob.glob(os.path.join(teams_dir, "*.json"))):
        data = json.load(open(path, encoding="utf-8"))
        number = data.get("country")
        if "teams" not in data or number is None or number >= CUSTOM_FILE:
            continue
        stem = os.path.splitext(os.path.basename(path))[0]
        for t in data["teams"]:
            team = t["team"]
            teams[(stem, team["team_name"].rstrip())] = team
            for index, p in enumerate(t["players"]):
                players.append({
                    "name": p["player_name"].rstrip(), "position": p["position"],
                    "price": p["price"], "headline": headline_skills(p),
                    "country": team["country_number"], "ordinal": team["team_ordinal"],
                    "index": index, "team": team["team_name"].rstrip(),
                })
    players.sort(key=lambda p: (-p["price"], -p["headline"], p["name"]))
    return players, teams


def best_xi(players):
    taken, squad = set(), []
    for want in LINEUP_442 + BENCH:
        want = want if isinstance(want, tuple) else (want,)
        for p in players:
            if p["position"] in want and id(p) not in taken:
                taken.add(id(p))
                squad.append(p)
                break
        else:
            sys.exit("ghost_teams.py: nobody for %s" % "/".join(POSITIONS[w] for w in want))
    return squad


def kit(teams, where):
    stem, name, which = where
    team = teams.get((stem, name))
    if not team:
        sys.exit("ghost_teams.py: no %s in %s for a kit" % (name, stem))
    return [team["%s_%s" % (which, f)] for f in KIT_FIELDS]


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_c(path, name, spec, squad, home, away):
    lines = [
        "/* ghost_teams_data.c -- GENERATED by scripts/ghost_teams.py --c; do not edit.",
        " * Ghost teams by reference: each player's team file, team and player number, and the",
        " * names the game checks when it builds the team (src/ghost_teams.c). */",
        "",
        '#include "ghost_teams.h"',
        "",
        "const GhostTeam g_ghostBestXI = {",
        "    %s, %s," % (c_string(name), c_string(spec["coach"])),
        "    { %s },   /* home: %s */" % (", ".join(map(str, home)), spec["home_kit"][1]),
        "    { %s },   /* away: %s */" % (", ".join(map(str, away)), spec["away_kit"][1]),
        "    {",
    ]
    for slot, p in enumerate(squad):
        lines.append("        { %3d, %3d, %2d, %-19s %-25s },   /* %2d %-2s price %d */" % (
            p["country"], p["ordinal"], p["index"], c_string(p["team"]) + ",",
            c_string(p["name"]), slot + 1, POSITIONS[p["position"]], p["price"]))
    lines += ["    },", "};", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--teams", default=default_teams_dir())
    ap.add_argument("--c", metavar="FILE", help="write the C references")
    args = ap.parse_args()
    if not os.path.isdir(args.teams):
        sys.exit("ghost_teams.py: no team database at %s (--teams DIR)" % args.teams)

    players, teams = read(args.teams)
    name, spec = "BEST XI", TEAMS["BEST XI"]
    squad = best_xi(players)
    for slot, p in enumerate(squad):
        print("%2d %-2s %-22s %-18s price %d, %d headline skills" % (
            slot + 1, POSITIONS[p["position"]], p["name"], p["team"], p["price"], p["headline"]))
    if args.c:
        write_c(args.c, name, spec, squad, kit(teams, spec["home_kit"]),
                kit(teams, spec["away_kit"]))
        print("wrote", args.c)


if __name__ == "__main__":
    main()
