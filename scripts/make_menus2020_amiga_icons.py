#!/usr/bin/env python3
"""make_menus2020_amiga_icons.py -- the menus2020 mod's pictures for the Amiga (SWOS United).

    scripts/make_menus2020_amiga_icons.py

On the PC the main menu's entries draw their .bmp "image" (src/menu_extras.c, each colour the
nearest in the palette on screen). The Amiga reads no .bmp and has its menus' 16 colours only
(SWOS2.s menuPalette), so this maps each picture the main menu names
(bin/mods/menus2020/data_json/menus/swosMainMenu.json, its committed .bmp files) to the nearest
of menu colours 1..15 at BUILD time -- black and magenta stay see-through, as on the PC -- and
writes src/menus2020_amiga_icons.inc: per picture its size and one character a pixel ('0' clear,
'1'..'F' a menu colour), drawn by src/mod_menus2020.c through United_PutPixel.

The output is COMMITTED (a build needs no Python): run this again after changing a picture or
the main menu's images, and commit what it writes.
"""
import json
import os
import struct
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOD = os.path.join(REPO, "bin", "mods", "menus2020")
MENU = os.path.join(MOD, "data_json", "menus", "swosMainMenu.json")
OUT = os.path.join(REPO, "src", "menus2020_amiga_icons.inc")

# SWOS2.s menuPalette ($0RGB, 4 bits a channel); 0 is the backdrop's, never drawn with.
MENU_PALETTE = [0x0001, 0x0AAB, 0x0FFF, 0x0102, 0x0621, 0x0A40, 0x0F71, 0x0667,
                0x0204, 0x0445, 0x0F00, 0x000F, 0x0702, 0x088F, 0x0380, 0x0FF0]
RGB = [((v >> 8 & 15) * 17, (v >> 4 & 15) * 17, (v & 15) * 17) for v in MENU_PALETTE]


def read_bmp(path):
    """A 24-bit BMP's pixels, top row first, as (r, g, b)."""
    with open(path, "rb") as f:
        d = f.read()
    if d[:2] != b"BM":
        sys.exit(f"{path}: not a BMP")
    off = struct.unpack_from("<I", d, 10)[0]
    w, h = struct.unpack_from("<ii", d, 18)
    bpp = struct.unpack_from("<H", d, 28)[0]
    if bpp != 24:
        sys.exit(f"{path}: {bpp} bits a pixel, 24 expected")
    stride = (w * 3 + 3) & ~3
    rows = []
    for y in range(abs(h)):
        src = y if h < 0 else abs(h) - 1 - y
        p = off + src * stride
        rows.append([(d[p + x * 3 + 2], d[p + x * 3 + 1], d[p + x * 3]) for x in range(w)])
    return w, abs(h), rows


def nearest(rgb):
    r, g, b = rgb
    best, bi = None, 1
    for i in range(1, 16):
        pr, pg, pb = RGB[i]
        dist = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if best is None or dist < best:
            best, bi = dist, i
    return bi


def main():
    with open(MENU, encoding="utf-8") as f:
        menu = json.load(f)
    pictures = []
    ordinal = 0
    for item in menu["items"]:
        if item.get("kind") != "entry":
            continue
        image = item.get("image")
        if image:
            pictures.append((ordinal, image, item.get("image_x", -1), item.get("image_y", -1)))
        ordinal += 1

    out = ["/* GENERATED by scripts/make_menus2020_amiga_icons.py -- do not edit by hand.",
           " * The menus2020 main menu's pictures in the Amiga's 16 menu colours: per entry with an",
           " * \"image\", its place in the entry's box (-1 centred) and one character a pixel ('0' clear,",
           " * '1'..'F' a menu colour). src/mod_menus2020.c draws them. */", ""]
    names = []
    for ordinal, image, ix, iy in pictures:
        path = os.path.join(MOD, image)
        if not os.path.exists(path):
            print(f"skipped (missing): {image}")
            continue
        w, h, rows = read_bmp(path)
        ident = "k_pic_" + os.path.splitext(os.path.basename(image))[0]
        out.append(f"static const char {ident}[] =")
        for row in rows:
            line = "".join("0" if px in ((0, 0, 0), (255, 0, 255)) else "%X" % nearest(px) for px in row)
            out.append(f'    "{line}"')
        out.append(";")
        names.append((ordinal, ident, w, h, ix if ix is not None else -1, iy if iy is not None else -1, image))
        print(f"entry {ordinal}: {image} {w}x{h}")
    out.append("")
    out.append("static const struct { int16_t entry, w, h, x, y; const char *pix; } k_pictures[] = {")
    for ordinal, ident, w, h, ix, iy, image in names:
        out.append(f"    {{ {ordinal}, {w}, {h}, {ix}, {iy}, {ident} }},     /* {image} */")
    out.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
